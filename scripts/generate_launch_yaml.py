#!/usr/bin/env python3

import argparse
from pathlib import Path
from typing import Final

DATASETS: Final = {
    "aflw19": ("face_alignment", "aflw19_farl.yaml"),
    "ibug300w": ("face_alignment", "ibug300w_farl.yaml"),
    "wflw": ("face_alignment", "wflw_farl.yaml"),
    "celebm": ("face_parsing", "celebm_farl.yaml"),
    "lapa": ("face_parsing", "lapa_farl.yaml"),
}
TOTAL_BATCH_SIZE: Final = 40


def generate_launch_yaml(
    dataset: str,
    input_resolution: int,
    num_gpus: int,
    mode: str,
    checkpoint_path: str,
) -> str:
    if dataset not in DATASETS:
        choices = ", ".join(sorted(DATASETS))
        raise ValueError(f"unsupported dataset {dataset!r}; choose from: {choices}")
    if input_resolution <= 0:
        raise ValueError("input resolution must be positive")
    if num_gpus <= 0:
        raise ValueError("number of GPUs must be positive")
    if TOTAL_BATCH_SIZE % num_gpus != 0:
        raise ValueError(f"number of GPUs must divide {TOTAL_BATCH_SIZE} exactly")
    if mode not in {"finetune", "frozen"}:
        raise ValueError("mode must be either 'finetune' or 'frozen'")
    if not checkpoint_path:
        raise ValueError("checkpoint path must not be empty")

    package, trainer = DATASETS[dataset]
    optimizer = "refine_backbone" if mode == "finetune" else "freeze_backbone"
    freeze_visual = "True" if mode == "frozen" else "False"
    return f"""# Generated by scripts/generate_launch_yaml.py

package: farl.experiments.{package}

class: farl.experiments.distributed.CustomDistributedGPURun
local_run:
  $PARSE('./trainers/{trainer}',
    cfg_file=FILE,
    train_data_ratio=None,
    batch_size={TOTAL_BATCH_SIZE // num_gpus},
    model_type='base',
    model_path={repr(checkpoint_path)},
    input_resolution={input_resolution},
    head_channel=768,
    optimizer_name={repr(optimizer)},
    freeze_visual={freeze_visual},
    enable_amp=False)
"""


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a FaRL Blueprint distributed-training YAML file."
    )
    parser.add_argument("--dataset", required=True, choices=sorted(DATASETS))
    parser.add_argument("--input-resolution", required=True, type=int)
    parser.add_argument("--num-gpus", required=True, type=int)
    parser.add_argument("--mode", required=True, choices=("finetune", "frozen"))
    parser.add_argument("--checkpoint-path", required=True)
    parser.add_argument(
        "--output-path",
        required=True,
        type=Path,
        help="exact path of the YAML file to create",
    )
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    content = generate_launch_yaml(
        dataset=args.dataset,
        input_resolution=args.input_resolution,
        num_gpus=args.num_gpus,
        mode=args.mode,
        checkpoint_path=args.checkpoint_path,
    )
    output_path = args.output_path
    if output_path.exists():
        raise FileExistsError(f"refusing to overwrite existing file: {output_path}")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    print(output_path)


if __name__ == "__main__":
    main()
